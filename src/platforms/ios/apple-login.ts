import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { exec } from "../../utils/shell.js";

/** Internal lane in the generated Fastfile (templates/Fastfile.ejs). */
export const APPLE_LOGIN_LANE = "shipyard_apple_login";

export interface AppleLoginResult {
  status: "logged-in" | "failed" | "lane-missing";
  error?: string;
}

/** Fastfiles generated before the login lane existed do not have it: init regenerates them. */
export async function hasAppleLoginLane(projectDir: string): Promise<boolean> {
  try {
    const fastfile = await readFile(join(projectDir, "fastlane", "Fastfile"), "utf8");
    return fastfile.includes(`lane :${APPLE_LOGIN_LANE}`);
  } catch {
    return false;
  }
}

/**
 * Phase 1 of an iOS submit with an Apple ID: runs the login lane on the user's real terminal, so
 * fastlane can ask for the password (CredentialsManager::AccountManager stores it in the keychain
 * as deliver.<user>) and the 2FA code (spaceship then caches the session cookie under
 * ~/.fastlane/spaceship/<user>/cookie). The upload that follows is fully piped and reuses both.
 * Only call when isInteractive() is true.
 */
export async function appleLogin(opts: { projectDir: string; user: string }): Promise<AppleLoginResult> {
  if (!(await hasAppleLoginLane(opts.projectDir))) {
    return {
      status: "lane-missing",
      error: `fastlane/Fastfile has no ${APPLE_LOGIN_LANE} lane (generated by an older rn-shipyard). Run 'rn-shipyard init' again to regenerate it`,
    };
  }
  try {
    const r = await exec("fastlane", ["ios", APPLE_LOGIN_LANE], {
      cwd: opts.projectDir,
      foreground: true,
      env: { FASTLANE_USER: opts.user },
    });
    if (r.exitCode === 0) return { status: "logged-in" };
    return { status: "failed", error: `Apple login failed (fastlane exit ${r.exitCode}); see the output above` };
  } catch (err) {
    return { status: "failed", error: err instanceof Error ? err.message : String(err) };
  }
}
