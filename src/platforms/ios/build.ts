/** Marker comment in the generated build lane (signing + build number); older Fastfiles lack it. */
export const IOS_SIGNING_MARKER = "shipyard-ios-signing";

export interface IosBuildOptions {
  config: PlatformIosConfig;
  outputDir: string;
  appName: string;
  /** May contain BUILD_NUMBER_TOKEN */
  outputName: string;
  projectDir: string;
  /** Next build number from the local counter (the lane may raise it above TestFlight's latest) */
  buildNumber: number;
  /** --build-number was given: use it as is (still checked against TestFlight by the lane) */
  buildNumberOverride?: boolean;
  /** ios/ is tracked in git: the project and Info.plist the lane edits are restored afterwards */
  restoreNativeFiles?: boolean;
  json: boolean;
  /** Whether the user's terminal may be used for the up-front prompts (match repo clone) */
  interactive: boolean;
  /** eas.json build-profile env, passed to fastlane (never contains rn-shipyard's own secrets) */
  profileEnv?: Record<string, string>;
  warn?: (message: string) => void;
  info?: (message: string) => void;
}

export interface BuildResult {
  status: "success" | "error";
  artifactPath?: string;
  durationSeconds: number;
  error?: string;
  /** Set when the failure has a machine-readable code (e.g. MATCH_REPO_AUTH_FAILED) */
  errorCode?: string;
  /** The build number the lane used (also when the build failed after choosing it) */
  buildNumber?: number;
  /** Latest TestFlight build number the lane saw, when App Store Connect could be read */
  testflightLatest?: number;
}

export async function buildIos(opts: IosBuildOptions): Promise<BuildResult> {
  const started = Date.now();
  const fail = (err: ShipyardError): BuildResult => ({
    status: "error",
    durationSeconds: Math.round((Date.now() - started) / 1000),
    error: `${err.message}. ${err.fix}`,
    errorCode: err.code,
  });

  let target;
  try {
    target = await findIosWorkspace(opts.projectDir);
  } catch (err) {
    if (err instanceof ShipyardError) {
      return {
        status: "error",
        durationSeconds: Math.round((Date.now() - started) / 1000),
        error: `${err.message}. ${err.fix}`,
      };
    }
    throw err;
  }

  // A Fastfile from an older rn-shipyard has no signing/build-number step: building with it would
  // bring the "requires a development team" failure back, so say so instead.
  try {
    const fastfile = await readFile(join(opts.projectDir, "fastlane", "Fastfile"), "utf-8");
    if (!fastfile.includes(IOS_SIGNING_MARKER)) {
      return fail(
        new ShipyardError(
          "FASTFILE_OUTDATED",
          "fastlane/Fastfile was generated by an older rn-shipyard and its iOS build lane does not set up signing or the build number",
          "Run 'rn-shipyard init' again to regenerate it"
        )
      );
    }
  } catch {
    // no Fastfile: fastlane reports it
  }

  // Phase 1: everything that may prompt (git/ssh credentials for the Match repo) runs now, on
  // the user's terminal. Phase 2, the build lane, is fully piped and never prompts.
  let matchRepo;
  try {
    matchRepo = await prepareMatchRepo({
      gitUrl: opts.config.matchGitUrl,
      interactive: opts.interactive,
    });
  } catch (err) {
    if (err instanceof ShipyardError) return fail(err);
    throw err;
  }
  try {
    return await runIosBuild(opts, target, matchRepo?.env);
  } finally {
    await matchRepo?.dispose();
  }
}

/** Phase 2: the build lane, piped and non-interactive. `matchRepoEnv`: makes git read the Match repo from the local clone. */
async function runIosBuild(
  opts: IosBuildOptions,
  target: { workspace: string; scheme: string },
  matchRepoEnv: Record<string, string> | undefined
): Promise<BuildResult> {
  // A tracked ios/ belongs to the user: the lane edits project.pbxproj and Info.plist, so put
  // them back byte for byte afterwards, whatever happens (also on SIGINT/SIGTERM/SIGHUP).
  let restore: (() => Promise<void>) | undefined;
  /** absolute path -> sha256 of what the lane wrote (from its SHIPYARD_WROTE lines) */
  const laneWrote = new Map<string, string>();
  let cleanup: ReturnType<typeof registerCleanup> | undefined;
  if (opts.restoreNativeFiles) {
    const names: string[] = [];
    for (const n of await iosLaneTouchedFiles(opts.projectDir, target.workspace)) {
      try {
        await access(join(opts.projectDir, n));
        names.push(n);
      } catch {
        // not there: nothing to restore
      }
    }
    const snapshot = await snapshotFiles(opts.projectDir, names);
    restore = async () => {
      // A file that is neither the original nor what the lane wrote was changed by someone else
      // during the build: keep a copy before the restore overwrites it.
      for (const [name, before] of snapshot) {
        if (before === null) continue;
        const now = await readFile(join(opts.projectDir, name)).catch(() => null);
        if (now === null || now.equals(before)) continue;
        const wroteSha = laneWrote.get(join(opts.projectDir, name));
        if (wroteSha !== undefined && sha256(now) === wroteSha) continue;
        const dir = join(opts.projectDir, ".shipyard", "backup");
        const copy = join(dir, `${name.replace(/[\\/]/g, "_")}.${new Date().toISOString().replace(/[:.]/g, "-")}`);
        try {
          await mkdir(dir, { recursive: true });
          await writeFile(copy, now);
          opts.warn?.(`${name} was changed during the build by something other than rn-shipyard: your version is saved as ${join(".shipyard", "backup", copy.split("/").pop()!)} before ${name} is restored`);
        } catch {
          opts.warn?.(`${name} was changed during the build and could not be backed up; restoring it anyway`);
        }
      }
      const report = await restoreFiles(opts.projectDir, snapshot);
      if (report.restored.length > 0) {
        opts.info?.(`Restored ${report.restored.join(", ")} (ios/ is tracked in git; the build had modified it)`);
      }
      for (const name of report.failed) opts.warn?.(`Could not restore ${name}: restore it manually with git checkout`);
    };
    cleanup = registerCleanup(restore, () => {
      restoreFilesSync(opts.projectDir, snapshot);
    });
  }

  let result;
  try {
    result = await runFastlane(
      "ios",
      "build",
      {
        // absolute: fastlane runs a lane body inside fastlane/, not the project root
        workspace: join(opts.projectDir, target.workspace),
        scheme: target.scheme,
        output_dir: opts.outputDir,
        output_name: opts.outputName,
        build_number: String(opts.buildNumber),
        build_number_override: opts.buildNumberOverride ? "true" : undefined,
      },
      {
        json: opts.json,
        projectDir: opts.projectDir,
        // profile env first: rn-shipyard's own values (the git redirect) win
        env: { ...opts.profileEnv, ...matchRepoEnv },
        // a Match repo URL may carry a token (https://<token>@host/...)
        redact: gitUrlSecrets(opts.config.matchGitUrl),
      }
    );
  } finally {
    if (cleanup) {
      if (result) collectWrote(result.output, laneWrote);
      await cleanup.run();
      cleanup.unregister();
    }
  }

  const buildNumber = firstMarker(result.output, "SHIPYARD_BUILD_NUMBER") ?? opts.buildNumber;
  const latest = firstMarker(result.output, "SHIPYARD_TESTFLIGHT_LATEST");

  if (result.success) {
    await recordIosBuildNumber(opts.projectDir, buildNumber);
    return {
      status: "success",
      artifactPath: `${opts.outputDir}/${opts.outputName.split(BUILD_NUMBER_TOKEN).join(String(buildNumber))}`,
      durationSeconds: result.durationSeconds,
      buildNumber,
      ...(latest !== undefined ? { testflightLatest: latest } : {}),
    };
  }

  return {
    status: "error",
    durationSeconds: result.durationSeconds,
    error: extractBuildError(result.output),
    buildNumber,
    ...(latest !== undefined ? { testflightLatest: latest } : {}),
  };
}

/**
 * The lane's own marker: fastlane's log line is "[hh:mm:ss]: NAME=value" (or just "NAME=value"
 * with FASTLANE_HIDE_TIMESTAMP). The FIRST such whole line wins: xcodebuild and script phases
 * print later and must not be able to spoof it.
 */
function firstMarker(output: string, name: string): number | undefined {
  const m = new RegExp(`^(?:\\[\\d{2}:\\d{2}:\\d{2}\\]: )?${name}=(\\d+)\\s*$`, "m").exec(output);
  return m ? Number(m[1]) : undefined;
}

function sha256(b: Buffer): string {
  return createHash("sha256").update(b).digest("hex");
}

/** Records the lane's SHIPYARD_WROTE lines (first per path) into `into`. */
function collectWrote(output: string, into: Map<string, string>): void {
  for (const m of output.matchAll(/^(?:\[\d{2}:\d{2}:\d{2}\]: )?SHIPYARD_WROTE ([0-9a-f]{64}) (.+?)\s*$/gm)) {
    if (!into.has(m[2])) into.set(m[2], m[1]);
  }
}
